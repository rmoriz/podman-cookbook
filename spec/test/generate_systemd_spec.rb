# frozen_string_literal: true

require 'spec_helper'

describe 'test::generate_systemd' do
  platform 'ubuntu', '24.04'
  step_into :podman_generate_systemd

  let(:unit) { "[Unit]\nDescription=Podman templated\n\n[Service]\nRestart=on-failure\n" }

  let(:chef_run) do
    ChefSpec::SoloRunner.new(
      platform: 'ubuntu',
      version: '24.04',
      step_into: %w(podman_generate_systemd)
    ).converge(described_recipe)
  end

  before do
    # No unit-name header in the output, as with --no-header.
    stub_podman(stdout_for: { 'generate systemd' => unit })
    chef_run
  end

  it 'emits the timeouts and dependencies' do
    command = podman_commands.find { |entry| entry.include?('generate systemd') }
    expect(command).to include('--start-timeout 30')
    expect(command).to include('--stop-timeout 45')
    expect(command).to include('--restart-policy on-failure')
    expect(command).to include('--restart-sec 5')
    expect(command).to include('--requires network-online.target')
    expect(command).to include('--no-header')
    # One positional only: `type` is inferred by Podman.
    expect(command).to end_with(' templated')
  end

  it 'implies --new for a template instead of passing --new=false' do
    command = podman_commands.find { |entry| entry.include?('generate systemd') }
    expect(command).to include('--new')
    expect(command).to include('--template')
  end

  it 'writes the unit under the derived template name' do
    expect(chef_run).to create_file('/tmp/generated-units/container-templated@.service').with(content: unit, mode: '0644')
  end

  it 'reloads systemd through the unit file notification' do
    file = chef_run.file('/tmp/generated-units/container-templated@.service')
    expect(file).to notify('execute[generate-systemd daemon-reload /tmp/generated-units]').to(:run).immediately
  end
end

describe 'test::generate_systemd with a header' do
  platform 'ubuntu', '24.04'
  step_into :podman_generate_systemd

  let(:chef_run) do
    ChefSpec::SoloRunner.new(
      platform: 'ubuntu',
      version: '24.04',
      step_into: %w(podman_generate_systemd)
    ).converge('test::generate_systemd')
  end

  before do
    stub_podman(stdout_for: { 'generate systemd' => "# autogenerated by Podman 6.2.0\n# Sun Nov 22 10:54:09 UTC 2026\n\n[Unit]\n" })
  end

  it 'drops the generation timestamp from the header' do
    expect(chef_run.file('/tmp/generated-units/container-templated@.service').content)
      .to eq("# autogenerated by Podman 6.2.0\n\n[Unit]\n")
  end
end
